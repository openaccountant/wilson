// ── I1: the rename changes nothing but names ─────────────────────────────────

type BaselineEntry = {
  classification: string; minRole: string; transports: string[]; surface: unknown; exposure: string;
  uiEffect: boolean | null; autosubmit: boolean | null; defaultPolicy: string; untrustedOutput: boolean;
  allowedPolicies: string[]; schemaDigest: string;
  readEstimates: Record<string, { rows: number; chars: number }> | null;
};
const BASE = baseline as unknown as Record<string, BaselineEntry>;
const currentOf = (old: string) => currentNameFor(old) ?? old;

describe('I1 baseline equivalence', () => {
  test('the baseline holds the 26 pre-rename names', () => {
    expect(Object.keys(BASE)).toHaveLength(26);
    expect(Object.keys(BASE).map(currentOf).sort()).toEqual(MCP_TOOL_CATALOG.map((d) => d.name).sort());
  });

  test('every attribute of def(new) equals baseline[old]', () => {
    for (const [old, b] of Object.entries(BASE)) {
      const d = byName.get(currentOf(old))!;
      const actual: unknown = {
          classification: d.classification, minRole: d.minRole, transports: [...d.transports], surface: d.surface,
          exposure: d.exposure, uiEffect: d.uiEffect ?? null, autosubmit: d.autosubmit ?? null,
          defaultPolicy: d.defaultPolicy, untrustedOutput: d.untrustedOutput, allowedPolicies: allowedPolicies(d),
        };
      const expected: unknown = {
        classification: b.classification, minRole: b.minRole, transports: b.transports, surface: b.surface,
        exposure: b.exposure, uiEffect: b.uiEffect, autosubmit: b.autosubmit,
        defaultPolicy: b.defaultPolicy, untrustedOutput: b.untrustedOutput, allowedPolicies: b.allowedPolicies,
      };
      expect(actual, old).toEqual(expected);
    }
  });

  test('digest unchanged for every http-mcp tool; the only changed digest is open_review_item (tab-only)', () => {
    const changed = Object.entries(BASE).filter(([old, b]) => schemaDigest(currentOf(old)) !== b.schemaDigest).map(([old]) => currentOf(old));
    expect(changed).toEqual(['open_review_item']);
    for (const name of changed) expect(byName.get(name)!.transports).not.toContain('http-mcp');
    for (const d of MCP_TOOL_CATALOG.filter((t) => t.transports.includes('http-mcp'))) {
      const old = Object.keys(BASE).find((o) => currentOf(o) === d.name)!;
      expect(schemaDigest(d.name), d.name).toBe(BASE[old]!.schemaDigest);
    }
  });
});

describe('I1b no retired name in catalog prose', () => {
  const UNDERSCORED = Object.keys(RETIRED_TOOL_NAMES).filter((n) => n.includes('_'));
  const exact = (name: string) => new RegExp(`(?<![A-Za-z0-9_])${name}(?![A-Za-z0-9_])`);

  const prose = (d: McpToolDef): string[] => [d.description, JSON.stringify(d.example), JSON.stringify(jsonSchemaFor(d.name))];

  test('descriptions, examples and zod .describe() strings', () => {
    for (const d of MCP_TOOL_CATALOG) {
      for (const text of prose(d)) {
        for (const old of UNDERSCORED) expect(exact(old).test(text), `${d.name} mentions ${old}`).toBe(false);
        expect(/`forecast`|use forecast|call forecast|forecast tool/.test(text), `${d.name} mentions the forecast tool`).toBe(false);
      }
    }
  });

  test('every error string in tool-catalog.ts (it is scanned as text)', () => {
    const text = readFileSync(join(import.meta.dir, '../mcp/tool-catalog.ts'), 'utf8');
    for (const old of UNDERSCORED) expect(exact(old).test(text), `tool-catalog.ts mentions ${old}`).toBe(false);
    expect(/`forecast`|use forecast|call forecast|forecast tool/.test(text)).toBe(false);
  });
});

// ── I13: no retired literal in runtime code ──────────────────────────────────

describe('I13 no retired literal in runtime code', () => {
  const SRC = join(import.meta.dir, '..');
  const UNDERSCORED = Object.keys(RETIRED_TOOL_NAMES).filter((n) => n.includes('_'));
  /** Chat, mirror, handoff and retired-name files: the places where these strings are the right vocabulary. */
  const ALLOWED = [
    'mcp/tool-names.ts',
    'mcp/judge-reads.ts',
    'mcp/confirmation-card.ts', // CHAT_TOOL_LABELS only
    'cli.ts',
  ];
  const ALLOWED_PREFIXES = [
    'dashboard/local-handoff', 'dashboard/ui/src/hybrid/', 'dashboard/ui/src/store/mirror-', 'dashboard/ui/src/store/sync-engine.ts',
    'tools/', 'agent/', 'skills/', 'orchestration/', 'components/', 'utils/', '__tests__/', 'dashboard/ui/node_modules/', 'dashboard/ui/dist/', 'dashboard/ui/spike/',
  ];

  function walk(dir: string, out: string[] = []): string[] {
    for (const e of readdirSync(dir)) {
      const p = join(dir, e);
      if (e === 'node_modules' || e === 'dist') continue;
      if (statSync(p).isDirectory()) walk(p, out);
      else if (/\.(ts|tsx)$/.test(e)) out.push(p);
    }
    return out;
  }

  test('no quoted or backticked retired name outside the allowed chat, mirror and handoff files', () => {
    const hits: string[] = [];
    let scanned = 0;
    for (const file of walk(SRC)) {
      const rel = relative(SRC, file);
      if (ALLOWED.includes(rel) || ALLOWED_PREFIXES.some((p) => rel.startsWith(p))) continue;
      scanned++;
      const text = readFileSync(file, 'utf8');
      for (const old of UNDERSCORED) {
        if (new RegExp(`(['"\`])${old}\\1`).test(text)) hits.push(`${rel}: ${old}`);
      }
    }
    expect(scanned).toBeGreaterThan(40); // the scan really ran over the mcp and dashboard sources
    expect(hits).toEqual([]);
  });
});

