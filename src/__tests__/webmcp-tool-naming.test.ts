/**
 * The WebMCP tool naming convention (specs/webmcp-tool-naming.md §1) enforced over the catalog, the collision rule
 * against chat tool names, and the invariants that say the rename changed nothing but names (I1, I1b, I11, I13, I14).
 * The baseline fixture was generated from the pre-rename catalog and is never regenerated by this change.
 */

// ── The convention ───────────────────────────────────────────────────────────

const STOP_WORDS = new Set('a an and by for from in into of on or the to with'.split(' '));

/** Stems, not whole segments: `judgements` must fail even though only `judgement` is listed (AR-P9). */
const BRITISH_STEMS = [
  'judgement', 'analyse', 'analysed', 'analyses', 'analysing', 'behaviour', 'cancell', 'catalogue', 'categoris',
  'centre', 'colour', 'defence', 'favour', 'labell', 'licence', 'modell', 'organis', 'summaris',
];

/** Words the trailing-`s` test misreads (status, analysis, ...). Empty today; each entry needs a one-line reason. */
const PLURALITY_EXCEPTIONS: Record<string, 'singular' | 'plural'> = {};

type Predicate = (def: Pick<McpToolDef, 'classification' | 'uiEffect'>) => boolean;
const isPageUi: Predicate = (d) => d.classification === 'page' && d.uiEffect === true;
/** One predicate per verb; a verb outside this table fails, and every def must satisfy its own verb's predicate. */
const VERB_PREDICATES: Record<string, Predicate> = {
  get: (d) => d.classification === 'read' || (d.classification === 'page' && d.uiEffect !== true),
  list: (d) => d.classification === 'read',
  search: (d) => d.classification === 'read',
  open: isPageUi,
  fill: isPageUi,
  set: (d) => d.classification === 'mutating',
  update: (d) => d.classification === 'mutating',
  categorize: (d) => d.classification === 'mutating',
  resolve: (d) => d.classification === 'mutating',
  create: (d) => d.classification === 'mutating',
  delete: (d) => d.classification === 'mutating',
  propose: (d) => d.classification === 'proposal',
};

function segments(name: string): { verb: string; object: string[] } {
  const [verb, ...object] = name.split('_');
  return { verb: verb!, object };
}

function pluralityOf(word: string): 'singular' | 'plural' {
  if (PLURALITY_EXCEPTIONS[word]) return PLURALITY_EXCEPTIONS[word]!;
  return word.endsWith('s') && !word.endsWith('ss') ? 'plural' : 'singular';
}

function britishStem(segment: string): string | undefined {
  return BRITISH_STEMS.find((stem) => segment.startsWith(stem));
}

function isArrayShape(shape: unknown): boolean {
  if (shape == null) return false;
  const s = shape as { _zod?: { def?: { type?: string } }; _def?: { type?: string; typeName?: string } };
  return (s._zod?.def?.type ?? s._def?.type) === 'array' || s._def?.typeName === 'ZodArray';
}

/** Why `def` breaks the convention, or null. Pure, so the self-tests below can feed it bad names. */
function namingViolation(def: Pick<McpToolDef, 'name' | 'classification' | 'uiEffect' | 'zodShape'>): string | null {
  const { name } = def;
  if (!/^[a-z]+(_[a-z]+){1,3}$/.test(name)) return 'N1 shape';
  if (name.length > 32) return 'N2 length';
  const { verb, object } = segments(name);
  const stop = object.find((o) => STOP_WORDS.has(o));
  if (stop) return `N3 stop word ${stop}`;
  const british = segments(name).object.concat(verb).find((s) => britishStem(s));
  if (british) return `N9 British spelling ${british}`;
  const predicate = VERB_PREDICATES[verb];
  if (!predicate) return `N4 verb ${verb} is not in the verb set`;
  if (!predicate(def)) return `N4 verb ${verb} does not fit classification ${def.classification}`;
  const last = object[object.length - 1]!;
  if (['list', 'search', 'fill'].includes(verb) && pluralityOf(last) !== 'plural') return `N5 ${last} should be plural`;
  if (['get', 'open', 'set', 'update', 'categorize', 'resolve', 'create', 'delete'].includes(verb) && pluralityOf(last) !== 'singular') {
    return `N6 ${last} should be singular`;
  }
  if (verb === 'propose') {
    const batch = isArrayShape(def.zodShape.items);
    if (batch !== (pluralityOf(last) === 'plural')) return `N7 ${last} must be ${batch ? 'plural' : 'singular'}`;
  }
  return null;
}

const byName = new Map(MCP_TOOL_CATALOG.map((d) => [d.name, d]));

describe('WebMCP naming convention (spec §1)', () => {
  test('catalog size and order are unchanged: 26 tools', () => {
    expect(MCP_TOOL_CATALOG).toHaveLength(26);
    expect(new Set(MCP_TOOL_CATALOG.map((d) => d.name)).size).toBe(26);
  });

  test('N1 shape: lower snake case, letters only, 2 to 4 segments', () => {
    for (const d of MCP_TOOL_CATALOG) expect(d.name, d.name).toMatch(/^[a-z]+(_[a-z]+){1,3}$/);
  });

  test('N2 length: at most 32 characters', () => {
    for (const d of MCP_TOOL_CATALOG) expect(d.name.length, d.name).toBeLessThanOrEqual(32);
  });

  test('N3 no stop words in the object', () => {
    for (const d of MCP_TOOL_CATALOG) expect(segments(d.name).object.filter((o) => STOP_WORDS.has(o)), d.name).toEqual([]);
  });

  test('N4 verb is in the verb set, and its predicate holds for the tool (both directions)', () => {
    for (const d of MCP_TOOL_CATALOG) {
      const { verb } = segments(d.name);
      expect(VERB_PREDICATES[verb], `${d.name}: verb ${verb} is not in the verb set`).toBeDefined();
      expect(VERB_PREDICATES[verb]!(d), `${d.name}: ${verb} vs ${d.classification}`).toBe(true);
    }
  });

  test('N4 reverse: every classification is reachable only through its listed verbs', () => {
    const verbsOf = (c: McpToolDef['classification']) => [...new Set(MCP_TOOL_CATALOG.filter((d) => d.classification === c).map((d) => segments(d.name).verb))].sort();
    expect(verbsOf('proposal')).toEqual(['propose']);
    expect(verbsOf('mutating').every((v) => ['set', 'update', 'categorize', 'resolve', 'create', 'delete'].includes(v))).toBe(true);
    expect(verbsOf('read').every((v) => ['get', 'list', 'search'].includes(v))).toBe(true);
    expect(verbsOf('page').every((v) => ['get', 'open', 'fill'].includes(v))).toBe(true);
  });

  test('N5 to N7 plurality of the last object segment', () => {
    for (const d of MCP_TOOL_CATALOG) {
      const { verb, object } = segments(d.name);
      const last = object[object.length - 1]!;
      if (['list', 'search', 'fill'].includes(verb)) expect(pluralityOf(last), d.name).toBe('plural');
      else if (verb === 'propose') expect(pluralityOf(last) === 'plural', d.name).toBe(isArrayShape(d.zodShape.items));
      else expect(pluralityOf(last), d.name).toBe('singular');
    }
    expect(Object.keys(PLURALITY_EXCEPTIONS)).toEqual([]);
  });

  test('N8 twins (names that differ only by a trailing s) share classification, minRole and defaultPolicy', () => {
    const names = new Set(MCP_TOOL_CATALOG.map((d) => d.name));
    const twins = MCP_TOOL_CATALOG.filter((d) => names.has(`${d.name}s`));
    expect(twins.map((d) => d.name)).toEqual(['propose_judgment']);
    for (const a of twins) {
      const b = byName.get(`${a.name}s`)!;
      expect([b.classification, b.minRole, b.defaultPolicy]).toEqual([a.classification, a.minRole, a.defaultPolicy]);
    }
  });

  test('N8b the twins differ in transports and exposure, so behavior must be keyed on those, never on the spelling', () => {
    const single = byName.get('propose_judgment')!;
    const batch = byName.get('propose_judgments')!;
    expect([single.exposure, single.transports.includes('http-mcp')]).toEqual(['declarative', false]);
    expect([batch.exposure, batch.transports.includes('http-mcp')]).toEqual(['imperative', true]);
  });

  test('N9 no British spellings (stem match), and the old name provably fails', () => {
    for (const d of MCP_TOOL_CATALOG) expect(segments(d.name).object.concat(segments(d.name).verb).filter((s) => britishStem(s)), d.name).toEqual([]);
    expect(namingViolation({ name: 'propose_judgements', classification: 'proposal', zodShape: byName.get('propose_judgments')!.zodShape })).toMatch(/^N9/);
  });

  test('the whole predicate accepts every catalog name and refuses known-bad ones', () => {
    for (const d of MCP_TOOL_CATALOG) expect(namingViolation(d), d.name).toBeNull();
    const shape = {};
    expect(namingViolation({ name: 'tax_flag', classification: 'mutating', zodShape: shape })).toMatch(/^N4/);
    expect(namingViolation({ name: 'navigate_to_tab', classification: 'page', uiEffect: true, zodShape: shape })).toMatch(/^N3|^N4/);
    expect(namingViolation({ name: 'list_transaction', classification: 'read', zodShape: shape })).toMatch(/^N5/);
    expect(namingViolation({ name: 'get_transactions', classification: 'read', zodShape: shape })).toMatch(/^N6/);
    expect(namingViolation({ name: 'set_x_y_z_w', classification: 'mutating', zodShape: shape })).toMatch(/^N1/);
    expect(namingViolation({ name: 'get_thing', classification: 'mutating', zodShape: shape })).toMatch(/^N4/);
  });
});

